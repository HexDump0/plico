// Metrics for the standard PDF fonts the engine stamps with, so the preview
// measures text exactly as `rust/plico-engine/src/stamps/standard_fonts.rs`
// does. Widths are thousandths of the font size, indexed by WinAnsiEncoding
// code minus 32, from Adobe's Core 14 AFM files.

export type FontFamily = 'helvetica' | 'times' | 'courier';

const highCodes: Record<string, number> = {
	'€': 0x80,
	'‚': 0x82,
	ƒ: 0x83,
	'„': 0x84,
	'…': 0x85,
	'†': 0x86,
	'‡': 0x87,
	ˆ: 0x88,
	'‰': 0x89,
	Š: 0x8a,
	'‹': 0x8b,
	Œ: 0x8c,
	Ž: 0x8e,
	'‘': 0x91,
	'’': 0x92,
	'“': 0x93,
	'”': 0x94,
	'•': 0x95,
	'–': 0x96,
	'—': 0x97,
	'˜': 0x98,
	'™': 0x99,
	š: 0x9a,
	'›': 0x9b,
	œ: 0x9c,
	ž: 0x9e,
	Ÿ: 0x9f
};

/// The WinAnsiEncoding code for a character, or undefined if the standard
/// fonts cannot draw it.
export function winAnsi(character: string): number | undefined {
	const code = character.codePointAt(0) ?? 0;
	if ((code >= 0x20 && code <= 0x7e) || (code >= 0xa0 && code <= 0xff)) return code;
	return highCodes[character];
}

/// The first character in `text` the standard fonts cannot draw.
export function undrawable(text: string): string | undefined {
	return [...text.replace(/\r?\n/g, '')].find((character) => winAnsi(character) === undefined);
}

export function capHeight(family: FontFamily, bold: boolean) {
	return family === 'helvetica' ? 0.718 : family === 'times' ? (bold ? 0.676 : 0.662) : 0.562;
}

/// Width in points at `size`.
export function textWidth(text: string, family: FontFamily, bold: boolean, size: number) {
	const widths =
		family === 'helvetica'
			? bold
				? helveticaBold
				: helvetica
			: family === 'times'
				? bold
					? timesBold
					: times
				: undefined;
	let total = 0;
	for (const character of text) {
		const code = winAnsi(character);
		if (code === undefined) continue;
		// Courier is monospaced: every defined glyph is 600 wide.
		total += widths ? widths[code - 32] : 600;
	}
	return (total / 1000) * size;
}

